#!/usr/bin/env node
/** License-safe exact-ref metadata projection; image bytes stay private. */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { lstatSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import { cleanProviderCommit } from './generate-world-asset-catalog.mjs';

const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
function requireValue(value, message) {
  if (!value) throw new Error(message);
}
function safeFile(root, relative) {
  requireValue(
    typeof relative === 'string' &&
      relative.length > 0 &&
      !/[\\:%?#]/.test(relative) &&
      relative.split('/').every((p) => p && p !== '.' && p !== '..'),
    'unsafe file'
  );
  let current = root;
  requireValue(
    lstatSync(current).isDirectory() && !lstatSync(current).isSymbolicLink(),
    'unsafe root'
  );
  for (const part of relative.split('/')) {
    current = path.join(current, part);
    requireValue(!lstatSync(current).isSymbolicLink(), 'symlink forbidden');
  }
  requireValue(lstatSync(current).isFile(), 'missing file');
  return readFileSync(current);
}
export async function generateItemThumbnailCatalog({
  providerRoot,
  output,
  runtimeRoot,
  checkPin,
}) {
  const commit = checkPin ?? cleanProviderCommit(providerRoot);
  requireValue(/^[0-9a-f]{40}$/.test(commit), 'invalid provider commit');
  const readProvider = (file) =>
    checkPin
      ? execFileSync('git', ['-C', providerRoot, 'show', `${commit}:${file}`], {
          maxBuffer: 32 * 1024 * 1024,
        })
      : safeFile(providerRoot, file);
  const bytes = readProvider('harness/catalogs/synty-item-thumbnails.json');
  const catalog = JSON.parse(bytes);
  const legacy =
    catalog.schemaVersion === 1 &&
    catalog.generatedBy === 'item-thumbnails@1.0.0';
  const itemOwned =
    catalog.schemaVersion === 2 &&
    catalog.generatedBy === 'item-thumbnails@2.0.0';
  requireValue(legacy || itemOwned, 'unsupported catalog');
  const dimension = itemOwned ? 512 : 128;
  const maxImageBytes = itemOwned ? 4 * 1024 * 1024 : 1024 * 1024;
  if (itemOwned) {
    requireValue(
      catalog.renderer &&
        Object.keys(catalog.renderer).sort().join(',') ===
          'id,sourceSha256,threeVersion' &&
        catalog.renderer.id === 'item-thumbnail-v2' &&
        /^[0-9a-f]{64}$/.test(catalog.renderer.sourceSha256) &&
        catalog.renderer.threeVersion === '0.181.2',
      'unsupported item renderer'
    );
  }
  const manifestBytes = readProvider(
    'harness/models/synty/weapons/manifest.json'
  );
  requireValue(
    hash(manifestBytes) === catalog.sourceManifestSha256,
    'source manifest drift'
  );
  const manifest = JSON.parse(manifestBytes);
  requireValue(
    catalog.items &&
      typeof catalog.items === 'object' &&
      !Array.isArray(catalog.items),
    'invalid items'
  );
  const refs = Object.keys(catalog.items).sort();
  requireValue(
    refs.length > 0 &&
      JSON.stringify(refs) ===
        JSON.stringify(Object.keys(manifest.items).sort()),
    'item roster differs'
  );
  const entries = {};
  for (const ref of refs) {
    requireValue(
      /^dnd5e:item:[a-z0-9]+(?:-[a-z0-9]+)*$/.test(ref),
      'invalid exact ref'
    );
    const row = catalog.items[ref];
    const thumb = row.thumbnail;
    const model = manifest.items[ref];
    requireValue(
      row.modelFile === model.path &&
        row.modelSha256 === model.sha256 &&
        /^weapons\/[a-z0-9-]+\.glb$/.test(row.modelFile),
      'model identity differs'
    );
    requireValue(
      hash(readProvider(`harness/models/synty/${row.modelFile}`)) ===
        row.modelSha256,
      'model bytes differ'
    );
    requireValue(
      thumb?.file === `thumbnails/items/${hash(ref)}.png` &&
        /^[0-9a-f]{64}$/.test(thumb.sha256),
      'invalid thumbnail path/hash'
    );
    requireValue(
      thumb.width === dimension &&
        thumb.height === dimension &&
        Number.isSafeInteger(thumb.sizeBytes) &&
        thumb.sizeBytes >= 24 &&
        thumb.sizeBytes <= maxImageBytes,
      'invalid thumbnail dimensions/size'
    );
    const verifyImage = (png) => {
      requireValue(
        png.length === thumb.sizeBytes && hash(png) === thumb.sha256,
        'image bytes differ'
      );
      requireValue(
        png.subarray(0, 8).equals(Buffer.from('89504e470d0a1a0a', 'hex')) &&
          png.readUInt32BE(16) === dimension &&
          png.readUInt32BE(20) === dimension,
        'image dimensions differ'
      );
    };
    verifyImage(readProvider(`harness/models/synty/${thumb.file}`));
    if (runtimeRoot) verifyImage(safeFile(runtimeRoot, thumb.file));
    entries[ref] = {
      url: `/models/synty/${thumb.file}?v=${thumb.sha256}`,
      sha256: thumb.sha256,
      width: thumb.width,
      height: thumb.height,
    };
  }
  const source = await format(
    `// Generated by scripts/generate-item-thumbnail-catalog.mjs. Do not edit.\nexport const GENERATED_ITEM_THUMBNAIL_PROVIDER = Object.freeze({commit: '${commit}', catalogSha256: '${hash(bytes)}'});\nexport interface ItemThumbnail { readonly url: string; readonly sha256: string; readonly width: number; readonly height: number; }\nexport const GENERATED_ITEM_THUMBNAILS: Readonly<Record<string, ItemThumbnail>> = Object.freeze(${JSON.stringify(entries)});\n`,
    { parser: 'typescript', singleQuote: true, trailingComma: 'es5' }
  );
  if (checkPin)
    requireValue(
      readFileSync(output, 'utf8') === source,
      'generated item catalog differs'
    );
  else {
    mkdirSync(path.dirname(output), { recursive: true });
    writeFileSync(output, source);
  }
  return { commit, itemCount: refs.length };
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  try {
    const args = new Map();
    for (let i = 2; i < process.argv.length; i += 2) {
      const key = process.argv[i],
        value = process.argv[i + 1];
      requireValue(
        [
          '--provider-root',
          '--output',
          '--runtime-root',
          '--check-pin',
        ].includes(key) &&
          value &&
          !args.has(key),
        'invalid argument'
      );
      args.set(key, value);
    }
    requireValue(
      args.has('--provider-root') && args.has('--output'),
      'provider-root and output required'
    );
    const result = await generateItemThumbnailCatalog({
      providerRoot: path.resolve(args.get('--provider-root')),
      output: path.resolve(args.get('--output')),
      runtimeRoot: args.get('--runtime-root'),
      checkPin: args.get('--check-pin'),
    });
    console.log(
      `Item thumbnails: verified ${result.itemCount} refs at ${result.commit}`
    );
  } catch (error) {
    console.error(String(error));
    process.exitCode = 1;
  }
}
