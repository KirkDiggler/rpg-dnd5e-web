#!/usr/bin/env -S tsx
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  lstatSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseGroundCatalog } from '../src/rendering/groundCatalog.ts';
import { cleanProviderCommit } from './generate-world-asset-catalog.mjs';
import {
  regularResourceFile,
  verifyOwnedResourceFiles,
  verifyRuntimeImage,
} from './runtime-image-resources.mjs';
const RUNTIME = 'harness/models/synty',
  MANIFEST = `${RUNTIME}/ground/manifest.json`;
const FORMAT_PATH = fileURLToPath(
  new URL('../src/generated/groundCatalogProvider.ts', import.meta.url)
);
const PRETTIER = fileURLToPath(
  new URL('../node_modules/prettier/bin/prettier.cjs', import.meta.url)
);
const fail = (message) => {
  throw new Error(`Ground catalog: ${message}`);
};
function exists(path) {
  try {
    lstatSync(path);
    return true;
  } catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
}
function realRoot(root) {
  if (lstatSync(root).isSymbolicLink() || !lstatSync(root).isDirectory())
    fail('root must be a real directory');
  return realpathSync(root);
}
function providerRuntime(root) {
  let path = root;
  for (const part of RUNTIME.split('/')) {
    path = join(path, part);
    if (lstatSync(path).isSymbolicLink())
      fail('provider runtime path contains a symlink');
  }
  return path;
}

/** expectedManifest comes from the pinned Git object, never moving HEAD. */
function readResources(runtimeRoot, expectedManifest) {
  realRoot(runtimeRoot);
  const path = join(runtimeRoot, 'ground/manifest.json');
  if (!exists(path)) {
    if (expectedManifest) fail('pinned ground manifest missing');
    verifyOwnedResourceFiles({
      modelRoot: runtimeRoot,
      subtree: 'ground',
      expected: new Set(),
    });
    return { catalogSha256: null };
  }
  const bytes = readFileSync(
    regularResourceFile(runtimeRoot, 'ground/manifest.json')
  );
  if (
    expectedManifest === null ||
    (expectedManifest && !expectedManifest.equals(bytes))
  )
    fail('runtime ground manifest differs from pinned provider');
  const parsed = parseGroundCatalog(JSON.parse(bytes.toString('utf8')));
  if (!parsed.ok) fail(parsed.reason);
  const expected = new Set(['ground/manifest.json']),
    images = new Map();
  for (const style of parsed.catalog.styles) {
    expected.add(style.diffuse);
    images.set(style.diffuse, {
      file: style.diffuse,
      sha256: style.sha256,
      width: style.width,
      height: style.height,
    });
  }
  for (const image of images.values())
    verifyRuntimeImage({ modelRoot: runtimeRoot, image, opaque: true });
  verifyOwnedResourceFiles({
    modelRoot: runtimeRoot,
    subtree: 'ground',
    expected,
  });
  return { catalogSha256: createHash('sha256').update(bytes).digest('hex') };
}
function render(commit, catalog) {
  if (!/^[a-f0-9]{40}$/.test(commit))
    fail('provider pin must be an exact commit');
  const source = `// Generated by scripts/generate-ground-catalog.mjs. Do not edit.\n// Identity is not a claim that this provider commit has merged.\nexport const GENERATED_GROUND_PROVIDER = Object.freeze({\n commit: ${JSON.stringify(commit)},\n catalogSha256: ${JSON.stringify(catalog.catalogSha256)} as string | null,\n});\n`;
  return execFileSync(
    process.execPath,
    [PRETTIER, '--stdin-filepath', FORMAT_PATH],
    {
      input: source,
      encoding: 'utf8',
      // The caller's ignore rules must not change the generated pin bytes.
      cwd: resolve(dirname(FORMAT_PATH), '../..'),
    }
  );
}
function verifyOutput(outputPath, source) {
  if (readFileSync(outputPath, 'utf8') !== source)
    fail('generated ground pin is stale; run ground:sync');
}
export function generateGroundCatalog({
  providerRoot,
  outputPath,
  runtimeRoot,
  check = false,
}) {
  const root = realRoot(providerRoot),
    commit = cleanProviderCommit(root),
    sourceRoot = providerRuntime(root),
    catalog = readResources(sourceRoot);
  if (runtimeRoot) {
    const expected =
      catalog.catalogSha256 === null
        ? null
        : readFileSync(join(sourceRoot, 'ground/manifest.json'));
    readResources(runtimeRoot, expected);
  }
  const source = render(commit, catalog);
  if (check) verifyOutput(outputPath, source);
  else {
    mkdirSync(dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, source);
  }
  return { providerCommit: commit, ...catalog };
}
export function checkPinnedGroundCatalog({
  providerRoot,
  commit,
  runtimeRoot,
  outputPath,
}) {
  const root = realRoot(providerRoot);
  cleanProviderCommit(root);
  if (!/^[a-f0-9]{40}$/.test(commit)) fail('pin must be an exact commit');
  const git = (args) =>
    execFileSync('git', ['-C', root, ...args], {
      stdio: ['ignore', 'pipe', 'pipe'],
      maxBuffer: 50 * 1024 * 1024,
    });
  if (
    git(['rev-parse', '--verify', `${commit}^{commit}`])
      .toString()
      .trim() !== commit
  )
    fail('pin is not a commit');
  let present = true;
  try {
    git(['cat-file', '-e', `${commit}:${MANIFEST}`]);
  } catch {
    present = false;
  }
  const expected = present ? git(['show', `${commit}:${MANIFEST}`]) : null;
  const catalog = readResources(runtimeRoot, expected);
  verifyOutput(outputPath, render(commit, catalog));
  return { providerCommit: commit, ...catalog };
}
function argument(name, required = true) {
  const i = process.argv.indexOf(name),
    value = i >= 0 ? process.argv[i + 1] : undefined;
  if (required && (!value || value.startsWith('--'))) fail(`missing ${name}`);
  return value;
}
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  const input = {
      providerRoot: argument('--provider-root'),
      outputPath: argument('--output'),
      runtimeRoot: argument('--runtime-root', false),
    },
    pin = argument('--check-pin', false);
  if (pin && !input.runtimeRoot) fail('--check-pin requires --runtime-root');
  const result = pin
    ? checkPinnedGroundCatalog({ ...input, commit: pin })
    : generateGroundCatalog({
        ...input,
        check: process.argv.includes('--check'),
      });
  console.log(
    `Ground catalog: ${result.providerCommit} (${result.catalogSha256 ?? 'catalog absent'})`
  );
}
