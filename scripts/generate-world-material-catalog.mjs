#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import {
  lstatSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { cleanProviderCommit } from './generate-world-asset-catalog.mjs';
import { readWorldMaterialCatalog } from './world-material-catalog.mjs';
const CATALOG = 'harness/catalogs/synty-world-materials.json';
const RUNTIME = 'harness/models/synty';
const FORMAT_PATH = fileURLToPath(
  new URL('../src/generated/worldMaterialCatalog.ts', import.meta.url)
);
const PRETTIER = fileURLToPath(
  new URL('../node_modules/prettier/bin/prettier.cjs', import.meta.url)
);
function fail(message) {
  throw new Error(`World material catalog: ${message}`);
}
function exists(path) {
  try {
    lstatSync(path);
    return true;
  } catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
}
function realRoot(root) {
  if (lstatSync(root).isSymbolicLink() || !lstatSync(root).isDirectory())
    fail('root must be a real directory');
  return realpathSync(root);
}
function emptyMaterials(root) {
  realRoot(root);
  const visit = (path) => {
    if (!exists(path)) return;
    const entry = lstatSync(path);
    if (entry.isSymbolicLink() || !entry.isDirectory())
      fail('unowned material resources without a catalog');
    for (const name of readdirSync(path)) visit(join(path, name));
  };
  visit(join(root, 'world-materials'));
  return { catalogSha256: null, materials: [] };
}
function providerPath(root, relative) {
  let current = root;
  for (const part of relative.split('/')) {
    current = join(current, part);
    if (exists(current) && lstatSync(current).isSymbolicLink())
      fail('provider catalog/runtime path contains a symlink');
  }
  return current;
}
function parse(catalogPath, modelRoot) {
  return exists(catalogPath)
    ? readWorldMaterialCatalog({ catalogPath, modelRoot })
    : emptyMaterials(modelRoot);
}
export function renderWorldMaterialCatalogModule({ commit, catalog }) {
  if (!/^[a-f0-9]{40}$/.test(commit))
    fail('provider commit must be an exact SHA');
  const source = `// Generated by scripts/generate-world-material-catalog.mjs. Do not edit.\nimport type { WorldSurfaceMaterial } from '../rendering/worldMaterialTypes';\n\nexport const GENERATED_WORLD_MATERIAL_PROVIDER = Object.freeze({\n commit: ${JSON.stringify(commit)},\n catalogSha256: ${JSON.stringify(catalog.catalogSha256)} as string | null,\n});\n\nexport const GENERATED_WORLD_MATERIALS: readonly WorldSurfaceMaterial[] = Object.freeze(${JSON.stringify(catalog.materials)} as WorldSurfaceMaterial[]);\n`;
  return execFileSync(
    process.execPath,
    [PRETTIER, '--stdin-filepath', FORMAT_PATH],
    { input: source, encoding: 'utf8' }
  );
}
function verifyOutput(outputPath, source) {
  if (readFileSync(outputPath, 'utf8') !== source)
    fail('generated catalog is stale; run world-materials:sync');
}
export function generateWorldMaterialCatalog({
  providerRoot,
  outputPath,
  runtimeRoot,
  check = false,
}) {
  const root = realRoot(providerRoot),
    commit = cleanProviderCommit(root);
  const catalogPath = providerPath(root, CATALOG);
  const catalog = parse(catalogPath, providerPath(root, RUNTIME));
  if (runtimeRoot) {
    const mirrored = parse(catalogPath, runtimeRoot);
    if (JSON.stringify(mirrored) !== JSON.stringify(catalog))
      fail('synchronized material catalog differs');
  }
  const source = renderWorldMaterialCatalogModule({ commit, catalog });
  if (check) verifyOutput(outputPath, source);
  else {
    mkdirSync(dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, source);
  }
  return {
    providerCommit: commit,
    catalogSha256: catalog.catalogSha256,
    materialCount: catalog.materials.length,
  };
}
/** Verify an assembled pinned runtime against the catalog from the actual Git
 * object, not provider HEAD. This path can ONLY check, never emit a pin. */
export function checkPinnedWorldMaterialCatalog({
  providerRoot,
  commit,
  runtimeRoot,
  outputPath,
}) {
  const root = realRoot(providerRoot);
  cleanProviderCommit(root);
  if (!/^[a-f0-9]{40}$/.test(commit)) fail('pin must be an exact commit');
  const git = (args) =>
    execFileSync('git', ['-C', root, ...args], {
      stdio: ['ignore', 'pipe', 'pipe'],
      maxBuffer: 50 * 1024 * 1024,
    });
  if (
    git(['rev-parse', '--verify', `${commit}^{commit}`])
      .toString()
      .trim() !== commit
  )
    fail('pin is not a commit');
  const scratch = mkdtempSync(join(tmpdir(), 'world-material-pin-'));
  try {
    const catalogPath = join(scratch, 'catalog.json');
    let present = true;
    try {
      git(['cat-file', '-e', `${commit}:${CATALOG}`]);
    } catch {
      present = false;
    }
    if (present)
      writeFileSync(catalogPath, git(['show', `${commit}:${CATALOG}`]));
    const catalog = parse(catalogPath, runtimeRoot);
    verifyOutput(
      outputPath,
      renderWorldMaterialCatalogModule({ commit, catalog })
    );
    return {
      providerCommit: commit,
      catalogSha256: catalog.catalogSha256,
      materialCount: catalog.materials.length,
    };
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}
function argument(name, required = true) {
  const i = process.argv.indexOf(name),
    value = i >= 0 ? process.argv[i + 1] : undefined;
  if (required && (!value || value.startsWith('--'))) fail(`missing ${name}`);
  return value;
}
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  const input = {
    providerRoot: argument('--provider-root'),
    outputPath: argument('--output'),
    runtimeRoot: argument('--runtime-root', false),
  };
  const pin = argument('--check-pin', false);
  if (pin && !input.runtimeRoot) fail('--check-pin requires --runtime-root');
  const result = pin
    ? checkPinnedWorldMaterialCatalog({ ...input, commit: pin })
    : generateWorldMaterialCatalog({
        ...input,
        check: process.argv.includes('--check'),
      });
  console.log(
    `World material catalog: ${result.materialCount} materials at ${result.providerCommit}${result.catalogSha256 ? '' : ' (catalog absent)'}`
  );
}
